# 04_report.R
# ---------------------------------------------------------------------------
# Collect the pipeline outputs into a short markdown summary of the synthetic
# run, and draw the data-quality figure. The README quotes from this file.
#
# Outputs
#   output/synthetic_run_summary.md
#   figures/data_quality_log.png
# ---------------------------------------------------------------------------

source(local({ d <- getwd(); while (!file.exists(file.path(d, "config.yml")) && dirname(d) != d) d <- dirname(d); file.path(d, "R", "utils.R") }))
suppressPackageStartupMessages(library(ggplot2))
cfg <- load_config()
out <- cfg$paths$output_dir
t0 <- Sys.time()

dq   <- fread(file.path(out, "data_quality_log.csv"))
flow <- fread(file.path(out, "cohort_flow.csv"))
rows <- fread(file.path(out, "cleaning_row_counts.csv"))
cmp  <- fread(file.path(out, "model_comparison.csv"))
dict <- fread(file.path(out, "feature_dictionary.csv"))
opt  <- fread(file.path(out, "bootstrap_optimism.csv"))
n_boot <- length(unique(opt$boot))

# ---------------------------------------------------------------------------
# Data-quality figure: issues caught per rule, by source table
# ---------------------------------------------------------------------------
dq_plot <- dq[n_rows > 0]
dq_plot[, label := sprintf("%s", gsub("_", " ", issue))]
dq_plot[, source_table := factor(source_table, levels = c("births", "gp_visits", "ed_presentations"))]
p <- ggplot(dq_plot, aes(n_rows, reorder(label, n_rows))) +
  geom_col(fill = "#2a78d6", width = 0.6) +
  geom_text(aes(label = n_rows), hjust = -0.25, size = 3.2, colour = "#52514e") +
  facet_grid(source_table ~ ., scales = "free_y", space = "free_y") +
  scale_x_continuous(expand = expansion(mult = c(0, 0.15))) +
  labs(title = "Linkage and plausibility issues detected",
       subtitle = sprintf("%d records flagged by %d rules on the raw synthetic extract", sum(dq$n_rows), sum(dq$n_rows > 0)),
       x = "Records flagged", y = NULL,
       caption = "Synthetic cohort with injected faults (R/00_simulate_cohort.R). Not study results.") +
  theme_minimal(base_size = 12) +
  theme(plot.background = element_rect(fill = "#fcfcfb", colour = NA),
        panel.grid.minor = element_blank(), panel.grid.major.y = element_blank(),
        panel.grid.major.x = element_line(colour = "#e1e0d9", linewidth = 0.3),
        strip.text.y = element_text(angle = 0, face = "bold", colour = "#0b0b0b"),
        plot.title = element_text(face = "bold"), plot.subtitle = element_text(colour = "#52514e"),
        plot.caption = element_text(colour = "#898781", hjust = 0))
ggsave(file.path(cfg$paths$figures_dir, "data_quality_log.png"), p, width = 9, height = 6, dpi = 150, bg = "#fcfcfb")

# ---------------------------------------------------------------------------
# Markdown summary
# ---------------------------------------------------------------------------
md_table <- function(dt) {
  dt <- as.data.table(dt)
  hdr <- paste0("| ", paste(names(dt), collapse = " | "), " |")
  sep <- paste0("|", paste(rep("---", ncol(dt)), collapse = "|"), "|")
  body <- apply(dt, 1, function(r) paste0("| ", paste(trimws(r), collapse = " | "), " |"))
  paste(c(hdr, sep, body), collapse = "\n")
}
f3 <- function(x) sprintf("%.3f", x)
f2 <- function(x) sprintf("%.2f", x)

cmp_md <- cmp[, .(
  Model = model_label,
  Predictors = n_predictors,
  `AUC apparent` = f3(auc_apparent),
  `AUC optimism-corrected` = f3(auc_optimism_corrected),
  `AUC hold-out (95% CI)` = sprintf("%s (%s-%s)", f3(auc_test), f3(auc_test_ci_low), f3(auc_test_ci_high)),
  `Brier` = f3(brier),
  `Scaled Brier` = f3(brier_scaled),
  `Cal. intercept` = f2(calibration_intercept),
  `Cal. slope` = f2(calibration_slope),
  `Net benefit @ 0.15` = sprintf("%.4f", net_benefit_at_threshold)
)]

groups <- dict[role == "predictor", .N, by = group][, sprintf("%s (%d)", group, N)]

lines <- c(
  "# Synthetic run summary",
  "",
  "Everything below was produced by running the pipeline on the **synthetic** cohort",
  "generated by `R/00_simulate_cohort.R`. None of these numbers are findings of the real study.",
  "",
  sprintf("Generated %s. Bootstrap resamples: %d.", format(Sys.time(), "%Y-%m-%d %H:%M"), n_boot),
  "",
  "## Cohort flow",
  "",
  md_table(flow[, .(Step = step, Children = n)]),
  "",
  "## Cleaning",
  "",
  md_table(rows),
  "",
  "## Data-quality log",
  "",
  md_table(dq[, .(Issue = issue, Table = source_table, Rows = n_rows, Rule = rule, Action = action)]),
  "",
  "## Features",
  "",
  sprintf("%d predictors: %s.", sum(dict$role == "predictor"), paste(groups, collapse = ", ")),
  "",
  "## Model comparison (hold-out set)",
  "",
  md_table(cmp_md),
  "",
  sprintf("Treat-all net benefit at threshold 0.15: %.4f.", cmp$net_benefit_treat_all[1]),
  ""
)
writeLines(lines, file.path(out, "synthetic_run_summary.md"))
cat(lines[grep("## Model comparison", lines):length(lines)], sep = "\n")
msg("04_report.R finished in %.1f s", as.numeric(Sys.time() - t0, units = "secs"))
